/* 卡片文字／關鍵字列裡出現的所有關鍵字（依辭典順序，不重複） */
function keywordsOn(d) {
  var found = [], text = (d.text || '') + ' ' + ((d.kw || []).join(' '));
  Object.keys(KEYWORDS).forEach(function (k) {
    if (text.indexOf(k) >= 0) found.push(k);
  });
  return found;
}
